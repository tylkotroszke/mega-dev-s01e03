import assert from 'node:assert/strict';
import fs from 'node:fs';
import { stripTypeScriptTypes } from 'node:module';

const root = new URL('../', import.meta.url);
const read = (p) => JSON.parse(fs.readFileSync(new URL(p, root), 'utf8'));
const code = fs.readFileSync(new URL('src/lib/kb/causes.ts', root), 'utf8');
const { uniqueById, groupByCause, causeOf, sameCause, dayFirst } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(code)).toString('base64')}`);
const raw = read('src/lib/data/reports-4471.json');
const tenants = fs.readdirSync(new URL('src/lib/data/tenants/', root)).map((name) => read(`src/lib/data/tenants/${name}`));
const tenantMap = new Map(tenants.map((t) => [t.handle, t]));
const tenantOf = (r) => tenantMap.get(r.tenant);
const reports = uniqueById(raw).filter((r) => r.mergedInto === 4471);
assert.equal(raw.length, 427);
assert.equal(reports.length, 412);
for (const report of raw) assert.deepEqual(report, reports.find((r) => r.id === report.id), 'duplicate rows must be identical');
const groups = groupByCause(reports, tenantOf);
assert.deepEqual(Object.fromEntries(groups.map((g) => [g.cause, g.reports.length])), { parser: 379, hint: 33 });
assert.equal(new Set(groups.flatMap((g) => g.reports.map((r) => r.id))).size, reports.length);
assert.equal(reports.filter((r) => r.meta.intakeTag !== causeOf(r, tenantOf(r))).length, 38);
assert.ok(tenants.every((t) => dayFirst(t.locale)));
const flagged = read('src/lib/data/desk-notes.json').oneDayMove;
assert.equal(flagged.length, 5);
assert.ok(flagged.every((id) => groups.find((g) => g.cause === 'parser').reports.some((r) => r.id === id)));
const hint = groups.find((g) => g.cause === 'hint').reports;
assert.deepEqual(Object.fromEntries(['alder.physio', 'copper.studio', 'pale.harbour'].map((t) => [t, hint.filter((r) => r.tenant === t).length])), { 'alder.physio': 12, 'copper.studio': 11, 'pale.harbour': 10 });
// Counterexamples to the documented subject-only rule; execute the original classifier.
const alder = tenantMap.get('alder.physio');
assert.equal(sameCause({ channel: 'form' }, alder, { channel: 'app' }, alder), false);
assert.equal(sameCause({ channel: 'app' }, tenantMap.get('kettle.books'), { channel: 'email' }, tenantMap.get('kettle.books')), true);
assert.equal(sameCause({ channel: 'email' }, undefined, { channel: 'email' }, undefined), false);
assert.equal(causeOf(reports.find((r) => r.id === 'R-41230'), tenantMap.get('copper.studio')), 'hint');
const received = reports.map((r) => r.receivedAt.slice(0, 10)).sort();
const merged = reports.map((r) => r.mergedAt.slice(0, 10)).sort();
assert.equal(received[0], '2026-04-01');
assert.equal(merged[0], '2026-07-02');
assert.equal(received.at(-1), '2026-10-04');
const monthly = Object.fromEntries([...new Set(received.map((d) => d.slice(0, 7)))].map((m) => [m, received.filter((d) => d.startsWith(m)).length]));
assert.deepEqual(monthly, { '2026-04': 56, '2026-05': 57, '2026-06': 66, '2026-07': 73, '2026-08': 68, '2026-09': 80, '2026-10': 12 });
const bodyCode = fs.readFileSync(new URL('src/lib/kb/body-evidence.ts', root), 'utf8');
const { bodyEvidence } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(bodyCode)).toString('base64')}`);
assert.equal(bodyEvidence({ id: 'example', body: 'Booked for 7 April. The invite says 4 July.' }, []), 'reported-swap');
assert.equal(bodyEvidence({ id: 'example', body: 'Booked for 7 April. The invite says 6 April.' }, []), 'other-description');
assert.equal(bodyEvidence({ id: 'example', body: 'Booked for 5 May. The invite says 5 May.' }, []), 'other-description');
assert.equal(bodyEvidence({ id: 'flagged', body: 'The invite arrived before the booking.' }, ['flagged']), 'flagged-time');
const evidenceTotals = Object.fromEntries(groups.map((g) => [g.cause, Object.fromEntries(['reported-swap', 'flagged-time', 'other-description'].map((kind) => [kind, g.reports.filter((r) => bodyEvidence(r, flagged) === kind).length]))]));
assert.deepEqual(evidenceTotals, { parser: { 'reported-swap': 370, 'flagged-time': 5, 'other-description': 4 }, hint: { 'reported-swap': 33, 'flagged-time': 0, 'other-description': 0 } });
const triageCode = fs.readFileSync(new URL('src/lib/kb/triage.ts', root), 'utf8');
const { problemOf } = await import(`data:text/javascript;base64,${Buffer.from(stripTypeScriptTypes(triageCode)).toString('base64')}`);
const workItems = Object.fromEntries(['parser', 'hint', 'temporal', 'unplaced'].map((kind) => [kind, reports.filter((r) => problemOf(r, causeOf(r, tenantOf(r)), flagged) === kind)]));
assert.deepEqual(Object.fromEntries(Object.entries(workItems).map(([k,rs])=>[k,rs.length])), { parser:374, hint:33, temporal:5, unplaced:0 });
assert.deepEqual(workItems.temporal.map(r=>r.id).sort(), [...flagged].sort());
assert.ok(workItems.parser.every(r=>!flagged.includes(r.id)));
assert.ok(workItems.hint.every(r=>!flagged.includes(r.id)));
assert.equal(Object.values(workItems).flat().length,412);
assert.equal(new Set(Object.values(workItems).flat().map(r=>r.id)).size,412);
assert.equal(problemOf({id:'flagged'}, 'parser', ['flagged']), 'temporal');
assert.equal(problemOf({id:'unknown'}, null, []), 'unplaced');
const viewSource = fs.readFileSync(new URL('src/lib/kb/ReviewEvidence.svelte', root), 'utf8');
assert.ok(!/\/issues\/\d+/.test(viewSource), 'Do not assume future GitHub issue numbers');
console.log('PASS: original routing retained for comparison; corrected 374/33/5 work items are exhaustive and disjoint, all temporal IDs excluded from mechanism tickets; body evidence, counterexamples, timeline and links checked.');
